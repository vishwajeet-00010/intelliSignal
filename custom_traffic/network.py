"""
IntelliSignal
custom_traffic/network.py

What the road itself allows.

Custom traffic lets a user describe demand lane by lane, so the form has to
know which movements each lane can actually make. That is a property of the
SUMO network, not a preference, and getting it wrong does not produce a
different simulation - it produces vehicles that cannot follow their route.

The intersection has four approaches with two incoming lanes each:

        lane 0  kerb-side   right turn  and  straight ahead
        lane 1  centre      straight ahead and left turn

Both lanes can go straight. Only lane 0 can turn right and only lane 1 can
turn left. This is read from `sumo/network/intersection.net.xml`, where the
connections from N2C are:

    fromLane 0 -> C2W (right),  fromLane 0 -> C2S (straight)
    fromLane 1 -> C2S (straight), fromLane 1 -> C2E (left)

`LANE_MOVEMENTS` below is the same statement in Python, and
`verify_against_network()` checks the two have not drifted apart.
"""

from __future__ import annotations

import os
import re
from typing import Dict, List, Tuple

from utils.config_loader import PROJECT_ROOT
from utils.scenario_builder import MOVEMENTS, NETWORK_FILE

APPROACHES: Tuple[str, ...] = ("north", "east", "south", "west")
MOVEMENT_ORDER: Tuple[str, ...] = ("right", "straight", "left")
LANES_PER_APPROACH = 2

#: Which movements each incoming lane can make.
LANE_MOVEMENTS: Dict[int, Tuple[str, ...]] = {
    0: ("right", "straight"),
    1: ("straight", "left"),
}

#: The lanes that can serve a given movement.
MOVEMENT_LANES: Dict[str, Tuple[int, ...]] = {
    "right": (0,),
    "straight": (0, 1),
    "left": (1,),
}

#: Speed limit of every incoming lane, in m/s and km/h. Read from the network
#: file at import time rather than written down twice.
DEFAULT_LANE_SPEED_MPS = 13.89


def _read_lane_speed() -> float:
    try:
        with open(NETWORK_FILE, "r", encoding="utf-8") as handle:
            text = handle.read()
    except OSError:
        return DEFAULT_LANE_SPEED_MPS
    match = re.search(r'<lane id="N2C_0"[^>]*speed="([0-9.]+)"', text)
    return float(match.group(1)) if match else DEFAULT_LANE_SPEED_MPS


LANE_SPEED_MPS: float = _read_lane_speed()
LANE_SPEED_KMH: float = round(LANE_SPEED_MPS * 3.6, 1)


# ---------------------------------------------------------------------------
def lane_id(approach: str, lane: int) -> str:
    """The SUMO lane id, e.g. ("north", 0) -> "N2C_0"."""
    if approach not in MOVEMENTS:
        raise ValueError("Unknown approach {!r}. Use one of {}.".format(
            approach, ", ".join(APPROACHES)))
    if lane not in LANE_MOVEMENTS:
        raise ValueError("Unknown lane index {!r}. Use 0 (kerb-side) or 1 "
                         "(centre).".format(lane))
    return "{}_{}".format(MOVEMENTS[approach][0], lane)


def lane_label(approach: str, lane: int) -> str:
    """How the lane is named in the interface."""
    side = "kerb-side" if lane == 0 else "centre"
    return "{} lane {} ({})".format(approach.capitalize(), lane, side)


def route_id(approach: str, movement: str) -> str:
    """The route id `utils/scenario_builder.py` writes for this movement."""
    return "{}_{}".format(approach, movement)


def route_edges(approach: str, movement: str) -> str:
    """The two edges of a movement, as SUMO wants them in a <route>."""
    incoming, outgoing = MOVEMENTS[approach]
    if movement not in outgoing:
        raise ValueError("{} has no {} movement.".format(approach, movement))
    return "{} {}".format(incoming, outgoing[movement])


def movements_for_lane(lane: int) -> Tuple[str, ...]:
    """The movements this lane is allowed to make, in display order."""
    allowed = LANE_MOVEMENTS[lane]
    return tuple(m for m in MOVEMENT_ORDER if m in allowed)


def all_lanes() -> List[Tuple[str, int]]:
    """Every (approach, lane) pair, in the order the interface shows them."""
    return [(approach, lane)
            for approach in APPROACHES
            for lane in range(LANES_PER_APPROACH)]


def kmh_to_mps(kmh: float) -> float:
    return float(kmh) / 3.6


def mps_to_kmh(mps: float) -> float:
    return float(mps) * 3.6


# ---------------------------------------------------------------------------
def verify_against_network() -> List[str]:
    """Check `LANE_MOVEMENTS` still matches the network file.

    Returns a list of disagreements, empty when the two agree. The network is
    generated by `sumo/network/build_network.py`, so it can change; a silent
    disagreement here would put vehicles on lanes that cannot serve their
    route, which SUMO reports as a teleport rather than as an error.
    """
    if not os.path.isfile(NETWORK_FILE):
        return ["network file not found: {}".format(
            os.path.relpath(NETWORK_FILE, PROJECT_ROOT))]

    with open(NETWORK_FILE, "r", encoding="utf-8") as handle:
        text = handle.read()

    problems: List[str] = []
    pattern = re.compile(
        r'<connection from="(\w+)" to="(\w+)" fromLane="(\d+)"[^>]*dir="(\w)"')
    found: Dict[Tuple[str, int], set] = {}
    direction_names = {"r": "right", "s": "straight", "l": "left"}

    for from_edge, _to_edge, from_lane, direction in pattern.findall(text):
        for approach, (incoming, _outs) in MOVEMENTS.items():
            if incoming != from_edge:
                continue
            movement = direction_names.get(direction)
            if movement:
                found.setdefault((approach, int(from_lane)), set()).add(movement)

    for approach in APPROACHES:
        for lane in range(LANES_PER_APPROACH):
            actual = found.get((approach, lane), set())
            expected = set(LANE_MOVEMENTS[lane])
            if actual != expected:
                problems.append(
                    "{}: network allows {} but LANE_MOVEMENTS says {}".format(
                        lane_id(approach, lane),
                        ", ".join(sorted(actual)) or "nothing",
                        ", ".join(sorted(expected))))
    return problems
