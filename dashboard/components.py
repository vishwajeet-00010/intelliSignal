def render_svg(svg: str, height: int = 470) -> None:
    """Render an inline SVG.

    Both `st.markdown(..., unsafe_allow_html=True)` and `st.html()` sanitise
    inline SVG in current Streamlit versions, which strips the intersection
    diagram down to an empty box. `streamlit.components.v1.html` renders the
    markup in a small sandboxed frame exactly as written, so the diagram
    appears. The frame is transparent and sized, so it is invisible as a frame.
    """
    document = (
        "<!doctype html><html><head><meta charset='utf-8'>"
        "<style>html,body{margin:0;padding:0;background:transparent;"
        "display:flex;justify-content:center;align-items:flex-start;}"
        "svg{max-width:100%;height:auto;}</style></head>"
        "<body>{svg}</body></html>".replace("{svg}", svg)
    )
    # st.iframe is the current API; st.components.v1.html is the fallback for
    # older Streamlit versions. The markup is generated by this project from
    # its own simulation data, never from user input.
    if hasattr(st, "iframe"):
        st.iframe(document, height=height)
        return
    import streamlit.components.v1 as components
    components.html(document, height=height, scrolling=False)


