def signal_readout(directions: Dict[str, str], subtitle: str = "") -> None:
    """The current NS / EW signal colours."""
    def lamp(name: str, key: str) -> str:
        colour = SIGNAL_COLORS.get(directions.get(key, "off"), SIGNAL_COLORS["off"])
        text = directions.get(key, "off").upper()
        return ('<div class="lamp"><span class="bulb" style="background:{c}">'
                "</span>{n}: {t}</div>".format(c=colour, n=name, t=text))

    st.markdown('<div class="is-signal">{}{}</div>'.format(
        lamp("NS", "NS"), lamp("EW", "EW")), unsafe_allow_html=True)
    if subtitle:
        st.markdown('<div class="is-caption">{}</div>'.format(subtitle),
                    unsafe_allow_html=True)


def agent_decision_panel(explanation: Optional[Dict[str, Any]],
                         placeholder_text: str = "") -> None:
    """The controller's reasoning for one decision.

    For the fixed-time plan it says that no traffic state is used. For the
    DQN it shows the two Q-values the decision was actually made from, so a
    panel member can see the numbers rather than only the outcome.
    """
    if explanation is None:
        st.markdown(
            '<div class="is-panel"><h4>Controller decision</h4><p>{}</p></div>'.format(
                html.escape(placeholder_text or "No decision to show yet.")),
            unsafe_allow_html=True)
        return

    state_rows = "".join(
        "<tr><td style='padding:2px 14px 2px 0;color:#6b7075'>{}</td>"
        "<td style='padding:2px 0;color:#1f2326'>{}</td></tr>".format(
            html.escape(str(k)),
            html.escape(fmt(v, 1) if isinstance(v, (int, float)) else str(v)))
        for k, v in explanation.get("state", {}).items())

    learned = explanation.get("is_learned", False)
    kind = "Learned policy" if learned else "Rule-based controller"
    uses_state = explanation.get("uses_traffic_state", None)
    if uses_state is False:
        kind += " — does not read the traffic state"

    # --- the Q-values, when the agent is a network ---------------------
    q_block = ""
    q_values = explanation.get("q_values")
    if q_values:
        chosen = explanation.get("env_action_name", "")
        cells = []
        for name, key in (("Q(keep)", "keep"), ("Q(switch)", "switch")):
            value = q_values.get(key)
            picked = chosen.upper() == key.upper()
            cells.append(
                '<div style="flex:1;padding:.5rem .7rem;border-radius:6px;'
                'background:{bg};border:1px solid {border}">'
                '<div style="font-size:.72rem;color:#6b7075;'
                'text-transform:uppercase;letter-spacing:.04em">{name}{mark}</div>'
                '<div style="font-size:1.05rem;font-weight:600;color:#1f2326">'
                "{value}</div></div>".format(
                    name=html.escape(name),
                    mark=" · chosen" if picked else "",
                    value=("{:+.4f}".format(value) if isinstance(value, (int, float))
                           else "—"),
                    bg="#eef5ff" if picked else "#f7f8f9",
                    border="#b9d4ff" if picked else "#e6e8ea"))
        q_block = ('<div style="display:flex;gap:.6rem;margin-top:.6rem">'
                   + "".join(cells) + "</div>")
        model = explanation.get("model_path", "")
        if model:
            q_block += ('<div class="is-caption" style="margin-top:.4rem">'
                        "Network: <code>{}</code></div>".format(
                            html.escape(os.path.basename(str(model)))))

    st.markdown(
        '<div class="is-panel">'
        "<h4>{agent} decision</h4>"
        '<p><strong>Action:</strong> {action} &nbsp;·&nbsp; {kind}</p>'
        '<p style="margin-top:.4rem">{reason}</p>'
        "{q_block}"
        '<table style="margin-top:.6rem;font-size:.82rem">{rows}</table>'
        "</div>".format(
            agent=html.escape(str(explanation.get("agent", "Controller"))),
            action=html.escape(str(explanation.get("action_name", "—"))),
            kind=html.escape(kind),
            reason=html.escape(str(explanation.get("reason", ""))),
            q_block=q_block,
            rows=state_rows),
        unsafe_allow_html=True)


