# Positions of each approach inside the 16-character SUMO signal state.
# Four controlled links per approach: North 0-3, East 4-7, South 8-11, West 12-15.
STATE_BLOCKS = {"north": (0, 4), "east": (4, 8), "south": (8, 12), "west": (12, 16)}


# ==========================================================================
# Signal state decoding - real data in, colours out
# ==========================================================================
def decode_signal_state(state: Optional[str]) -> Dict[str, str]:
    """Turn a 16-character SUMO signal state into a colour per approach.

    'G' and 'g' are green (protected and permissive), 'y' is yellow,
    everything else is red. Returns "off" when there is no state to decode.
    """
    if not state or len(state) < 16:
        return {name: "off" for name in STATE_BLOCKS}
    colours = {}
    for name, (start, end) in STATE_BLOCKS.items():
        block = state[start:end]
        if "y" in block.lower():
            colours[name] = "yellow"
        elif "g" in block.lower():
            colours[name] = "green"
        else:
            colours[name] = "red"
    return colours


def direction_states(state: Optional[str]) -> Dict[str, str]:
    """Collapse the four approaches into the NS and EW movements."""
    per_approach = decode_signal_state(state)
    def combine(a: str, b: str) -> str:
        if "yellow" in (a, b):
            return "yellow"
        if "green" in (a, b):
            return "green"
        if a == "off" and b == "off":
            return "off"
        return "red"
    return {
        "NS": combine(per_approach["north"], per_approach["south"]),
        "EW": combine(per_approach["east"], per_approach["west"]),
    }


