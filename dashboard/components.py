def kpi_card(label: str, value: str, unit: str = "", note: str = "") -> None:
    st.markdown(
        '<div class="is-kpi">'
        '<div class="label">{label}</div>'
        '<div class="value">{value}<span class="unit">{unit}</span></div>'
        '<div class="note">{note}</div>'
        "</div>".format(label=html.escape(label), value=html.escape(value),
                        unit=html.escape(unit), note=html.escape(note)),
        unsafe_allow_html=True,
    )


def kpi_row(run) -> None:
    """The four headline metrics of a run. Values come from the CSV."""
    if run is None:
        st.info("No results yet. Run a scenario from the **Simulation** page.")
        return
    metrics = run.metrics
    note = "{} · {}".format(scenario_label(run.scenario), run.source)
    columns = st.columns(4)
    with columns[0]:
        kpi_card("Average waiting time",
                 fmt(metrics.get("average_waiting_time"), 2), " sec", note)
    with columns[1]:
        kpi_card("Average queue length",
                 fmt(metrics.get("average_queue_length"), 2), " vehicles", note)
    with columns[2]:
        kpi_card("Throughput",
                 fmt(metrics.get("throughput"), 0), " vehicles", note)
    with columns[3]:
        kpi_card("Simulation time",
                 fmt(metrics.get("simulation_time"), 0), " sec", note)


def secondary_metrics(run) -> None:
    if run is None:
        return
    metrics = run.metrics
    columns = st.columns(4)
    with columns[0]:
        kpi_card("Vehicles simulated", fmt(metrics.get("vehicles"), 0))
    with columns[1]:
        kpi_card("Maximum queue", fmt(metrics.get("max_queue_length"), 0), " vehicles")
    with columns[2]:
        kpi_card("Still in network", fmt(metrics.get("vehicles_still_in_network"), 0),
                 " vehicles", "waiting when the run ended")
    with columns[3]:
        kpi_card("Teleports", fmt(metrics.get("teleports"), 0), "",
                 "0 means no artificial gridlock")


