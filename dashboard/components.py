def intersection_panel(signal: Optional[Dict[str, str]] = None,
                       caption: str = "") -> None:
    render_svg(intersection_svg(signal), height=470)
    note = ("Schematic diagram of the modelled intersection — this is "
            "<strong>not</strong> a SUMO rendering. Real SUMO screenshots are "
            "on the <strong>Results</strong> page.")
    if caption:
        note = html.escape(caption) + " " + note
    st.markdown('<div class="is-caption">{}</div>'.format(note),
                unsafe_allow_html=True)


