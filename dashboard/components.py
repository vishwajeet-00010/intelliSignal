def intersection_svg(signal: Optional[Dict[str, str]] = None,
                     queues: Optional[Dict[str, Any]] = None,
                     width: int = 430) -> str:
    """A schematic of the IntelliSignal intersection.

    This is a diagram, not a SUMO rendering. The signal-head colours are real
    whenever a recorded SUMO signal state is passed in; the vehicle marks are
    indicative and are labelled as such wherever the diagram is displayed.
    """
    signal = signal or {"NS": "off", "EW": "off"}
    ns = SIGNAL_COLORS.get(signal.get("NS", "off"), SIGNAL_COLORS["off"])
    ew = SIGNAL_COLORS.get(signal.get("EW", "off"), SIGNAL_COLORS["off"])

    road, grass, marking = "#33383e", "#e9edec", "#ffffff"
    label_ink, queue_ink = "#3d434a", "#1f2326"
    moving, waiting = "#3b6fb6", "#8d9298"
    car_ns = moving if signal.get("NS") == "green" else waiting
    car_ew = moving if signal.get("EW") == "green" else waiting

    def car(x, y, vertical, colour):
        w, h = (9, 15) if vertical else (15, 9)
        return ('<rect x="{:.0f}" y="{:.0f}" width="{}" height="{}" rx="2.5" '
                'fill="{}"/>'.format(x, y, w, h, colour))

    def queue_of(key):
        if not queues or queues.get(key) is None:
            return ""
        return str(int(queues[key]))

