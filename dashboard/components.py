#: How each metric is formatted in the comparison tables.
COMPARISON_METRICS = [
    ("average_waiting_time", "Average waiting time", "s / vehicle", 2),
    ("average_queue_length", "Average queue length", "vehicles", 2),
    ("max_queue_length", "Maximum queue length", "vehicles", 0),
    ("throughput", "Throughput", "vehicles", 0),
    ("vehicles_still_in_network", "Still in network", "vehicles", 0),
    ("teleports", "Teleports", "", 0),
]


def improvement_badge(percent: Optional[float]) -> str:
    """'+18.4 % better' / '-5.1 % worse' / 'n/a'.

    A negative improvement is shown as plainly as a positive one. The label
    says which direction it is, so a reader cannot mistake a worse result for
    a better one.
    """
    if percent is None:
        return '<span style="color:#6b7075">n/a</span>'
    colour = "#1a7f45" if percent > 0 else ("#b3261e" if percent < 0 else "#6b7075")
    word = "better" if percent > 0 else ("worse" if percent < 0 else "no change")
    return ('<span style="color:{c};font-weight:600">{p:+.1f} %</span>'
            '<span style="color:#6b7075"> {w}</span>'.format(
                c=colour, p=percent, w=word))


def comparison_table(rows: List[Dict[str, Any]],
                     left_label: str = "Fixed-Time",
                     right_label: str = "DQN",
                     left_key: str = "fixed_time",
                     right_key: str = "dqn") -> None:
    """Fixed-Time vs DQN, one row per metric, with the improvement column.

    `rows` comes from the controller - either from a live pair of dashboard
    runs or from the multi-seed evaluation CSVs. This function formats; it
    never computes an improvement of its own.
    """
    labels = {m[0]: (m[1], m[2], m[3]) for m in COMPARISON_METRICS}
    body = []
    for row in rows:
        metric = row.get("metric")
        label, unit, digits = labels.get(metric, (metric, "", 2))
        direction = ("lower is better" if row.get("lower_is_better", True)
                     else "higher is better")
        body.append(
            "<tr>"
            '<td style="padding:.45rem .8rem .45rem 0">{label}'
            '<div style="font-size:.7rem;color:#8a9097">{unit}{sep}{dir}</div></td>'
            '<td style="padding:.45rem .8rem;text-align:right;'
            'font-variant-numeric:tabular-nums">{left}</td>'
            '<td style="padding:.45rem .8rem;text-align:right;'
            'font-variant-numeric:tabular-nums;font-weight:600">{right}</td>'
            '<td style="padding:.45rem 0;text-align:right">{imp}</td>'
            "</tr>".format(
                label=html.escape(str(label)),
                unit=html.escape(unit), sep=" · " if unit else "",
                dir=direction,
                left=fmt(row.get(left_key), digits),
                right=fmt(row.get(right_key), digits),
                imp=improvement_badge(row.get("improvement_percent"))))

    st.markdown(
        '<div class="is-panel"><table style="width:100%;font-size:.88rem;'
        'border-collapse:collapse">'
        '<tr style="font-size:.72rem;color:#6b7075;text-transform:uppercase;'
        'letter-spacing:.05em;border-bottom:1px solid #e6e8ea">'
        '<th style="text-align:left;padding-bottom:.4rem">Metric</th>'
        '<th style="text-align:right;padding-bottom:.4rem">{left}</th>'
        '<th style="text-align:right;padding-bottom:.4rem">{right}</th>'
        '<th style="text-align:right;padding-bottom:.4rem">DQN improvement</th>'
        "</tr>{body}</table></div>".format(
            left=html.escape(left_label), right=html.escape(right_label),
            body="".join(body)),
        unsafe_allow_html=True)


def controller_badge(mode: str, model_name: str = "") -> None:
    """A clear statement of WHICH controller produced what is on screen."""
    is_dqn = mode == "dqn_adaptive"
    label = "DQN Adaptive (learned)" if is_dqn else "Fixed-Time (rule-based)"
    detail = (" · model <code>{}</code>".format(html.escape(model_name))
              if is_dqn and model_name else "")
    st.markdown(
        '<div style="display:inline-block;padding:.3rem .7rem;border-radius:999px;'
        'font-size:.78rem;font-weight:600;background:{bg};color:{fg};'
        'border:1px solid {border}">Controller: {label}</div>'
        '<span class="is-caption">{detail}</span>'.format(
            bg="#fdeceb" if is_dqn else "#eef5ff",
            fg="#8c1d18" if is_dqn else "#11427f",
            border="#f3c7c4" if is_dqn else "#b9d4ff",
            label=html.escape(label), detail=detail),
        unsafe_allow_html=True)


