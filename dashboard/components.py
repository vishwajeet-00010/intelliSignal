def status_lights(indicators: List[Dict[str, Any]]) -> None:
    """The three detected status indicators. Never faked - see the controller."""
    parts = []
    for item in indicators:
        colour = OK if item["ok"] else BAD
        parts.append(
            '<div class="is-status">'
            '<span class="is-dot" style="background:{c}"></span>'
            '<span>{label}</span>'
            '<span class="detail">{detail}</span>'
            "</div>".format(c=colour, label=html.escape(str(item["label"])),
                            detail=html.escape(str(item.get("detail", ""))))
        )
    st.markdown('<div class="is-status-row">{}</div>'.format("".join(parts)),
                unsafe_allow_html=True)


def section(title: str, subtitle: str = "") -> None:
    st.markdown('<div class="is-section">{}</div>'.format(html.escape(title)),
                unsafe_allow_html=True)
    if subtitle:
        st.markdown('<div class="is-section-sub">{}</div>'.format(html.escape(subtitle)),
                    unsafe_allow_html=True)


def badge(text: str, kind: str = "planned") -> str:
    return '<span class="is-badge {k}">{t}</span>'.format(
        k=kind, t=html.escape(text))


